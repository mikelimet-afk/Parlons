// Nationalities from the Places list: the masculine form is the headword, the feminine points to it.
(function () {
  const B = FR.BASICS; if (!B || !B.countries) return;
  const lines = [], forms = [];
  B.countries.forEach(c => {
    const [m, f] = String(c[3] || '').split(',').map(s => s.trim());
    if (!m) return;
    lines.push(m + '|from ' + c[1] + ' (nationality)|a');
    if (f && f !== m) forms.push(m + ':' + f + ' ' + f + 's' + (/s$/.test(m) ? '' : ' ' + m + 's'));
  });
  FR.DICT_MORE.push('\n#nations|Nationalities|Nationalités\n' + lines.join('\n') + '\n');
  FR.FORMS_RAW += ';' + forms.join(';');
})();
